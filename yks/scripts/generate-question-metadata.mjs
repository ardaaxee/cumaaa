import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const appRoot = resolve(here, '..');
const questionDir = resolve(appRoot, 'src/data/questions');
const outputFile = resolve(appRoot, 'src/data/questionMetadata.generated.ts');

const files = readdirSync(questionDir)
  .filter((name) => name.endsWith('.ts'))
  .sort((a, b) => a.localeCompare(b));

const subjectPattern = /^(tyt|ayt)-(turkce|matematik|geometri|fizik|kimya|biyoloji|tarih|cografya|felsefe|din)/;

const countsByTopic = {};
const filesByTopic = {};
const countsBySubject = {};
const filesBySubject = {};
const countsByExam = { TYT: 0, AYT: 0 };

for (const file of files) {
  const subjectMatch = file.match(subjectPattern);
  if (!subjectMatch) throw new Error(`Soru dosyasından ders kimliği çıkarılamadı: ${file}`);

  const subjectId = `${subjectMatch[1]}-${subjectMatch[2]}`;
  const exam = subjectId.startsWith('tyt-') ? 'TYT' : 'AYT';
  const modulePath = `./questions/${file}`;
  const source = readFileSync(resolve(questionDir, file), 'utf8');

  const constants = Object.fromEntries(
    [...source.matchAll(/\bconst\s+([A-Za-z_$][\w$]*)\s*=\s*['"`]([^'"`]+)['"`]\s*;/g)].map((match) => [match[1], match[2]]),
  );

  const topics = [...source.matchAll(/\btopic\s*:\s*(['"`][^'"`]+['"`]|[A-Za-z_$][\w$]*)/g)]
    .map((match) => {
      const expression = match[1];
      if (/^['"`]/.test(expression)) return expression.slice(1, -1);
      return constants[expression];
    })
    .filter(Boolean);

  if (!topics.length) throw new Error(`Soru bulunamadı veya topic alanı çözümlenemedi: ${file}`);

  countsBySubject[subjectId] = (countsBySubject[subjectId] ?? 0) + topics.length;
  countsByExam[exam] += topics.length;
  filesBySubject[subjectId] ??= [];
  filesBySubject[subjectId].push(modulePath);

  for (const topic of topics) {
    countsByTopic[topic] = (countsByTopic[topic] ?? 0) + 1;
    filesByTopic[topic] ??= [];
    if (!filesByTopic[topic].includes(modulePath)) filesByTopic[topic].push(modulePath);
  }
}

const sortObject = (value) =>
  Object.fromEntries(
    Object.entries(value)
      .sort(([a], [b]) => a.localeCompare(b))
      .map(([key, item]) => [key, Array.isArray(item) ? [...item].sort() : item]),
  );

const total = Object.values(countsBySubject).reduce((sum, count) => sum + count, 0);

const generated = `/* AUTO-GENERATED by scripts/generate-question-metadata.mjs. Do not edit manually. */
export const QUESTION_COUNT_TOTAL = ${total} as const;
export const QUESTION_COUNTS_BY_EXAM = ${JSON.stringify(sortObject(countsByExam), null, 2)} as const;
export const QUESTION_COUNTS_BY_SUBJECT: Readonly<Record<string, number>> = ${JSON.stringify(sortObject(countsBySubject), null, 2)};
export const QUESTION_COUNTS_BY_TOPIC: Readonly<Record<string, number>> = ${JSON.stringify(sortObject(countsByTopic), null, 2)};
export const QUESTION_FILES_BY_SUBJECT: Readonly<Record<string, readonly string[]>> = ${JSON.stringify(sortObject(filesBySubject), null, 2)};
export const QUESTION_FILES_BY_TOPIC: Readonly<Record<string, readonly string[]>> = ${JSON.stringify(sortObject(filesByTopic), null, 2)};
`;

writeFileSync(outputFile, generated, 'utf8');
console.log(`question metadata: ${total} soru, ${Object.keys(countsByTopic).length} konu, ${files.length} dosya`);
